def str_to_byte(scene_str: str) -> Tuple[int, str]:
    """Converts the first up to 8 characters of the given string to a byte.
    Returns the byte and the remainder of the string.
    """
    byte = 0
    bit = 0
    for c in scene_str:
        if c not in (' ', '.', '|'):
            byte |= (1 << (7 - bit))
        bit += 1
        if bit == 8:
            break
    return byte, scene_str[8:]


def scene_to_bytes(scene_str: str) -> tuple[ArrayType[int], int]:
    """Convert a scene string to bytes by packing the bytes column wise.
    First Byte is from 1st line of the string, 2nd byte is from 2nd line of the string.
    12th byte is then from the 1st line again 13th byte from the 2nd line again and so on.
    Returns the bytes as array.
    """
    lines = scene_str.splitlines()[1:]
    height = len(lines)
    if height != 11 and height != 12:
        raise ValueError(f'Scene height must be 11 or 12, but is {height}')


    print(f'Converting scene of height {height}')
    scene_bytes = array('B')
    column_count = 0
    while ''.join(lines).strip() != '':
        column_count += 1
        for line_nr in range(height):
            print(f'line {line_nr:2} -> {lines[line_nr]}')
            byte, remainder = str_to_byte(lines[line_nr])
            scene_bytes.append(byte)
            lines[line_nr] = remainder
    print(f'Schene has {column_count} byte columns.')
    return scene_bytes, column_count


